"""查询关键词提取：把用户问题切成用于「关键词路召回」的词。

**为什么要有单独一条关键词路**：纯向量检索是语义匹配，对**编号、型号、专有名词**
（ISO27001、SQL-2000、工号规则）不敏感 —— 字面精确出现的内容反而不容易被召回。
jieba 提词后去 MySQL 做字面匹配（LIKE），两条路的候选再由 `fusion.rrf_merge` 融合。

jieba 用**搜索模式**（`cut_for_search`）：它会额外切出长词的子词
（"中华人民共和国" → 中华/华人/人民/共和国/…），对召回是好事 ——
召回阶段宁可多给候选，精度交给后面的 reranker 负责。
"""

import logging

logger = logging.getLogger(__name__)

# 停用词：高频虚词 / 疑问词，拿去做 LIKE 只会捞出一堆噪声。
# 刻意保持**很短**：像"几天""多少"这类词在业务问句里是有信息量的
# （"年假几天"），不能按通用停用词表一刀切 —— 这里只删真正没内容的。
STOPWORDS = frozenset({
    "的", "了", "是", "在", "和", "与", "及", "或", "有", "没", "不",
    "我", "你", "他", "她", "它", "我们", "你们", "他们", "咱们",
    "这", "那", "这些", "那些", "这个", "那个", "这边", "那边",
    "什么", "哪些", "哪个", "哪儿", "哪里", "怎么", "怎样", "如何",
    "可以", "能否", "是否", "请问", "一下", "帮我", "想知道", "介绍一下", "告诉",
    "吗", "呢", "啊", "吧", "呀", "哦", "嗯", "嘛", "哇",
})

# 🔴 领域词表：**jieba 的通用词典不认识企业制度词汇** ——
# 实测"年假几天"会被切成 ['年', '假', '几天']，"年假"这个核心业务词直接消失
# （然后因为"单字过滤"，关键词路对这句话等于什么都没提）。
# 所以建一份制度领域词表，在初始化时 add_word 进 jieba ——
# 这是关键词提取在企业语料上真正可用的一步，不是锦上添花。
DOMAIN_WORDS = (
    # 假期
    "年假", "事假", "病假", "婚假", "产假", "陪产假", "丧假", "探亲假",
    "调休", "假期", "请假", "休假", "加班", "补休",
    # 薪酬福利
    "薪酬", "工资", "薪资", "社保", "公积金", "补贴", "补助", "奖金",
    "绩效", "年终奖", "福利", "津贴", "报销", "差旅", "住宿费", "发票",
    # 考勤
    "考勤", "打卡", "工时", "迟到", "早退", "旷工", "排班", "值班",
    # 员工生命周期
    "入职", "离职", "转正", "试用期", "竞业", "续签", "解聘", "调岗", "晋升",
    # 常见制度对象
    "审批", "流程", "制度", "规范", "细则", "手册", "额度", "上限",
    "保密", "信息安全", "密码", "账号", "权限", "日志", "备份",
)

_jieba_ready = False


def _ensure_jieba():
    """首次调用时初始化 jieba（延迟导入 + 加载领域词），之后是零开销。"""
    global _jieba_ready
    if _jieba_ready:
        return

    import jieba

    jieba.setLogLevel(logging.WARNING)  # 关掉它默认往 stderr 打的初始化日志
    for word in DOMAIN_WORDS:
        jieba.add_word(word)
    _jieba_ready = True


def warmup() -> None:
    """预热 jieba：把词典构建提前到进程启动时（实测首次调用 ~0.8s，之后 0）。

    为什么要有它：`RAG_HYBRID_ENABLED` 默认开，不预热的话这笔成本就落在
    **每个新进程的第一个提问**上（用户白等一次）；挂到 lifespan 里预热，
    成本从"第一个用户"转移到"启动时刻付一次"（见 app/__init__.py 的 _lifespan）。
    """
    _ensure_jieba()


def extract_keywords(query: str, limit: int = 8) -> list[str]:
    """把查询切成关键词：保序去重，过滤停用词与**所有单字**。

    返回 `[]` 表示这句话提不出可用关键词（全是虚词/符号）——
    调用方应当**跳过关键词路**，而不是拿空列表去查。

    单字一律过滤（无论中英文数字）：`LIKE '%的%'` 这类匹配没有任何区分度，
    一个热门单字能把半库内容都捞回来 —— 宁可这条查询只走向量路。
    """
    text = (query or "").strip()
    if not text:
        return []

    _ensure_jieba()
    import jieba

    out: list[str] = []
    seen: set[str] = set()
    for raw in jieba.cut_for_search(text):
        word = raw.strip()
        if len(word) < 2 or word in seen or word in STOPWORDS:
            continue
        seen.add(word)
        out.append(word)
        if len(out) >= limit:
            break
    return out
